import assert from 'node:assert/strict';import {readFile,readdir} from 'node:fs/promises';
import {portalUrl} from '../github/portal-config.js';
assert.ok(portalUrl,'github/portal-config.js must name the site URL');
const html=await readFile('docs/index.html','utf8');
assert.match(html,new RegExp(`http-equiv="refresh" content="0; url=${portalUrl}/"`));
assert.match(html,/location\.replace\(.*location\.hash\)/,'redirect must preserve #/ routes');
assert.equal(await readFile('docs/404.html','utf8'),html,'404 page must redirect too');
assert.match(await readFile('docs/sw.js','utf8'),/unregister\(\)/,'old Pages service worker must remove itself');
const files=(await readdir('docs')).sort();assert.deepEqual(files,['.nojekyll','404.html','index.html','sw.js'],'docs/ must contain only the redirect');
console.log('PASS: GitHub Pages redirects every route to '+portalUrl);
